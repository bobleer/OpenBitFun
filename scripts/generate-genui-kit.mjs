// Compiles the NativeUI card kit (`src/nsh-ui/genui-kit/kit.tsx`) with the
// card compiler (`openbitfun-native-ui`) into the factory the desktop runner
// embeds (`src/apps/desktop-nsh/native/src/genui_kit.generated.js`).
//
//   node scripts/generate-genui-kit.mjs           write the factory
//   node scripts/generate-genui-kit.mjs --check   fail when it is stale

import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const source = new URL('../src/nsh-ui/genui-kit/kit.tsx', import.meta.url);
const target = new URL('../src/apps/desktop-nsh/native/src/genui_kit.generated.js', import.meta.url);

const factory = execFileSync(
  'cargo',
  ['run', '--quiet', '-p', 'openbitfun-native-ui', '--example', 'compile'],
  { cwd: root, input: readFileSync(source), encoding: 'utf8', windowsHide: true, maxBuffer: 16 * 1024 * 1024 },
);

const output = [
  '// Generated by scripts/generate-genui-kit.mjs from src/nsh-ui/genui-kit/kit.tsx.',
  '// The NativeUI card kit (`openbitfun/genui`) as a card factory. Do not edit by hand.',
  factory.trim(),
  '',
].join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('genui_kit.generated.js is stale: run `node scripts/generate-genui-kit.mjs`.');
    process.exit(1);
  }
  console.log('genui kit factory is current');
} else {
  writeFileSync(target, output);
  console.log(`wrote ${fileURLToPath(target)}`);
}
